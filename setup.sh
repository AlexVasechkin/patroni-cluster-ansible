#!/usr/bin/env bash
# ============================================================
# setup.sh — подготовка окружения перед первым запуском
#
# Что делает:
#   1. Генерирует SSH-ключевую пару для Ansible
#   2. Собирает Docker-образы
#   3. Запускает контейнеры
#   4. Добавляет хосты в ~/.ssh/known_hosts (чтобы Ansible не спрашивал)
# ============================================================

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SSH_DIR="$SCRIPT_DIR/ssh"

echo "========================================"
echo " Patroni Cluster — первоначальная настройка"
echo "========================================"

# -----------------------------------------------------------
# Шаг 1: Генерация SSH-ключей
# -----------------------------------------------------------
echo ""
echo "[1/4] Генерируем SSH-ключи для Ansible..."

if [[ -f "$SSH_DIR/id_rsa" ]]; then
    echo "  Ключи уже существуют, пропускаем."
else
    mkdir -p "$SSH_DIR"
    ssh-keygen -t rsa -b 4096 -f "$SSH_DIR/id_rsa" -N "" -C "ansible@patroni-cluster"
    echo "  Ключи созданы: $SSH_DIR/id_rsa (private), $SSH_DIR/id_rsa.pub (public)"
fi

# -----------------------------------------------------------
# Шаг 2: Сборка Docker-образов
# -----------------------------------------------------------
echo ""
echo "[2/4] Собираем Docker-образы (может занять несколько минут)..."
cd "$SCRIPT_DIR"
docker compose build

# -----------------------------------------------------------
# Шаг 3: Запуск контейнеров
# -----------------------------------------------------------
echo ""
echo "[3/4] Запускаем контейнеры..."
docker compose up -d

echo "  Ждём 10 секунд, пока systemd поднимется в контейнерах..."
sleep 10

# -----------------------------------------------------------
# Шаг 4: Добавление хостов в known_hosts
# -----------------------------------------------------------
echo ""
echo "[4/4] Добавляем SSH host-ключи в ~/.ssh/known_hosts..."

PORTS=(2221 2222 2223 2224 2225 2226 2227)
for port in "${PORTS[@]}"; do
    # Удаляем старые записи (на случай пересборки)
    ssh-keygen -R "[localhost]:$port" 2>/dev/null || true
    # Добавляем новые
    ssh-keyscan -p "$port" -H localhost >> ~/.ssh/known_hosts 2>/dev/null
    echo "  Добавлен localhost:$port"
done

echo ""
echo "========================================"
echo " Готово! Инфраструктура запущена."
echo "========================================"
echo ""
echo "Проверить статус контейнеров:"
echo "  docker compose ps"
echo ""
echo "Проверить SSH-доступ (пример):"
echo "  ssh -p 2221 -i ssh/id_rsa ansible@localhost hostname"
echo ""
echo "Следующий шаг:"
echo "  cd ansible && ansible -i inventory.ini all -m ping"
echo ""
